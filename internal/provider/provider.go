// bearerServiceFor selects the token source via the shared support
// library: the client_credentials grant when fully configured, otherwise
// the local awctl credential store as the development fallback. Partial
// client credentials are an error naming the gaps.
func bearerServiceFor(config authwiseProviderModel) (bearer.Service, error) {

	svc, err := supportcreds.Select(supportcreds.SelectParams{
		TokenURL:     stringOr(config.TokenURL, "AUTHWISE_TOKEN_URL"),
		ClientID:     stringOr(config.ClientID, "AUTHWISE_CLIENT_ID"),
		ClientSecret: stringOr(config.ClientSecret, "AUTHWISE_CLIENT_SECRET"),
		Audience:     stringOr(config.Audience, "AUTHWISE_AUDIENCE"),
		Hint:         "no valid credentials: run `awctl auth login` for the local development store, or set token_url, client_id, and client_secret (or the AUTHWISE_TOKEN_URL / AUTHWISE_CLIENT_ID / AUTHWISE_CLIENT_SECRET environment variables)",
	})
	if err != nil {
		return nil, fmt.Errorf("%w; set the provider attributes or the AUTHWISE_* environment variables", err)
	}
	return svc, nil
}

// stringOr returns the attribute value, falling back to the environment
// variable when the attribute is null or unknown.
func stringOr(v types.String, env string) string {
	if !v.IsNull() && !v.IsUnknown() {
		return v.ValueString()
	}
	return os.Getenv(env)
}

// Configure implements provider.Provider: it builds the authenticated gRPC
// client and hands tf.ProviderData to every generated resource and data
// source.
func (p *AuthwiseProvider) Configure(ctx context.Context, req provider.ConfigureRequest, resp *provider.ConfigureResponse) {

	var config authwiseProviderModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	endpoint := stringOr(config.Endpoint, "AUTHWISE_ENDPOINT")
	if endpoint == "" {
		resp.Diagnostics.AddAttributeError(path.Root("endpoint"),
			"missing endpoint",
			"set the endpoint attribute or the AUTHWISE_ENDPOINT environment variable")
		return
	}

	bearerService, err := bearerServiceFor(config)
	if err != nil {
		resp.Diagnostics.AddAttributeError(path.Root("client_id"),
			"incomplete client_credentials configuration", err.Error())
		return
	}

	transport := credentials.NewTLS(&tls.Config{MinVersion: tls.VersionTLS12})
	if config.Insecure.ValueBool() {
		transport = insecure.NewCredentials()
	}

	dial := func(target string) (*grpc.ClientConn, error) {
		return grpc.NewClient(target,
			grpc.WithTransportCredentials(transport),
			grpc.WithChainUnaryInterceptor(
				authwise.NewBearerCredentialsInterceptor(bearerService),
				warningInterceptor,
			),
		)
	}

	conn, err := dial(endpoint)
	if err != nil {
		resp.Diagnostics.AddError("cannot create gRPC client", err.Error())
		return
	}

	guardConn, guardConfigured, err := guardConnFor(config, dial)
	if err != nil {
		resp.Diagnostics.AddAttributeError(path.Root("guard_endpoint"), "cannot create guard-control gRPC client", err.Error())
		return
	}

	defaults := map[string]string{}
	for attr, v := range map[string]types.String{
		"tenant_id":   config.TenantID,
		"issuer_id":   config.IssuerID,
		"realm_id":    config.RealmID,
		"audience_id": config.AudienceID,
	} {
		if !v.IsNull() && !v.IsUnknown() {
			defaults[attr] = v.ValueString()
		}
	}

	providerData := &tfruntime.ProviderData{
		Clients: map[string]any{
			"identity": userContactClient{newAppearanceDefaultClient(identitypb.NewAuthwiseIdentityServiceClient(conn))},
			"access":   accesspb.NewAuthwiseAccessServiceClient(conn),

			guardClientKey:            guardpb.NewGuardControlServiceClient(guardConn),
			guardTenantAdminClientKey: guardpb.NewGuardTenantAdminServiceClient(guardConn),
			guardNodeClientKey:        guardpb.NewGuardNodeServiceClient(guardConn),
			guardConfiguredKey:        guardConfigured,
		},
		Defaults: defaults,
	}

	resp.ResourceData = providerData
	resp.DataSourceData = providerData
}

// Resources implements provider.Provider with the generated constructors,
// substituting the hand-written wrappers that add behavior the generator does
// not express, plus the resources whose shapes are beyond it.
func (p *AuthwiseProvider) Resources(ctx context.Context) []func() resource.Resource {
	return guardWrap(ctx, append(substitute(ctx, generated.Resources(), map[string]func() resource.Resource{
		accessBindingTypeName:     newAccessBindingResource,
		realmTypeName:             newRealmResource,
		factorTypeName:            newFactorResource,
		appearanceProfileTypeName: newAppearanceProfileResource,
		guardTenantTypeName:       newGuardTenantResource,
		guardInviteTypeName:       newGuardInviteResource,
		guardNodeTypeName:         newGuardNodeResource,
	}),
		newSecretResource,
		newRealmAuthenticationPolicyResource,
		newAssetContentResource,
		newGuardNodeGrantsResource,
	))
}

// substitute replaces generated constructors with wrappers, matched on the
// Terraform type name each resource reports rather than on list position.
func substitute(ctx context.Context, generated []func() resource.Resource, wrappers map[string]func() resource.Resource) []func() resource.Resource {

	out := make([]func() resource.Resource, 0, len(generated))

	for _, factory := range generated {
		resp := &resource.MetadataResponse{}
		factory().Metadata(ctx, resource.MetadataRequest{ProviderTypeName: providerTypeName}, resp)
		if w, ok := wrappers[resp.TypeName]; ok {
			factory = w
		}
		out = append(out, factory)
	}

	return out
}

// factorTypeName is the Terraform type of the generated factor resource,
// wrapped to report kit's warnings.
const factorTypeName = "authwise_factor"

func newFactorResource() resource.Resource {
	return &warningResource{inner: generated.NewFactorResource()}
}

// DataSources implements provider.Provider with the generated constructors
// plus the hand-written ones.
func (p *AuthwiseProvider) DataSources(ctx context.Context) []func() datasource.DataSource {
	return guardDataSourceWrap(ctx, append(generated.DataSources(), newSecretDataSource, newRealmAuthenticationContextSchemaDataSource))
}
