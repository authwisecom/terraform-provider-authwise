var _ provider.Provider = &AuthwiseProvider{}

// AuthwiseProvider manages Authwise identity objects over the published
// gRPC API. Most resources and data sources are generated by tfinfra from
// the spec table in gen/main.go; the rest are hand-written in this package
// (authwise_secret, authwise_realm_authentication_policy) or wrap a
// generated one (authwise_access_binding, authwise_realm).
type AuthwiseProvider struct {
	// version is set to the provider version on release, "dev" when built
	// locally, and "test" in acceptance testing.
	version string
}

type authwiseProviderModel struct {
	Endpoint      types.String `tfsdk:"endpoint"`
	GuardEndpoint types.String `tfsdk:"guard_endpoint"`
	TokenURL      types.String `tfsdk:"token_url"`
	ClientID      types.String `tfsdk:"client_id"`
	ClientSecret  types.String `tfsdk:"client_secret"`
	Audience      types.String `tfsdk:"audience"`
	Insecure      types.Bool   `tfsdk:"insecure"`

	// Scope identifier defaults; per-resource attributes override them.
	TenantID   types.String `tfsdk:"tenant_id"`
	IssuerID   types.String `tfsdk:"issuer_id"`
	RealmID    types.String `tfsdk:"realm_id"`
	AudienceID types.String `tfsdk:"audience_id"`
}

// New returns the provider factory, stamped with the release version.
func New(version string) func() provider.Provider {
	return func() provider.Provider {
		return &AuthwiseProvider{version: version}
	}
}

// providerTypeName prefixes every resource and data source type.
const providerTypeName = "authwise"

// Metadata implements provider.Provider.
func (p *AuthwiseProvider) Metadata(_ context.Context, _ provider.MetadataRequest, resp *provider.MetadataResponse) {
	resp.TypeName = providerTypeName
	resp.Version = p.version
}

