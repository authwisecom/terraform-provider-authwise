package main

import (
	"flag"
	"terraform-provider-authwise/gen/generate"

	"google.golang.org/protobuf/compiler/protogen"

	"github.com/dave/jennifer/jen"
	"github.com/rs/zerolog"
)


func main() {
	var flags flag.FlagSet
	loglevel := flags.Int("loglevel", 1, "loglevel available at https://pkg.go.dev/github.com/rs/zerolog@v1.28.0?utm_source=gopls#Level")
	protogen.Options{
		ParamFunc: flags.Set,
	}.Run(func(gen *protogen.Plugin) error {
		zerolog.SetGlobalLevel(zerolog.Level(*loglevel))
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			generateFile(gen, f)
		}
		return nil
	})
}

// generateFile generates a _ascii.pb.go file containing gRPC service definitions.
func generateFile(gen *protogen.Plugin, file *protogen.File) {
	schemaFile := file.GeneratedFilenamePrefix + "_schema.go"
	sf := jen.NewFile(string(file.GoPackageName))
	for _, m := range file.Messages {
		generate.Schema(sf, m)
	}

	sg := gen.NewGeneratedFile(schemaFile, file.GoImportPath)
	sg.P("// Code generated by protoc-gen-terraform. DO NOT EDIT.")
	sg.P(sf.GoString())

	modelFile := file.GeneratedFilenamePrefix + "_model.go"
	mf := jen.NewFile(string(file.GoPackageName))
	for _, m := range file.Messages {
		generate.Model(mf, m)
	}

	mg := gen.NewGeneratedFile(modelFile, file.GoImportPath)
	mg.P("// Code generated by protoc-gen-terraform. DO NOT EDIT.")
	mg.P(mf.GoString())
}
